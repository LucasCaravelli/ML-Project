r"""Generate report-ready tables (LaTeX snippets) and figures (PDFs) from
the canonical baseline / oracle artifacts.

Pure aggregation: reads only JSON files under artifacts/baselines/,
artifacts/oracle/, and artifacts/splits/. No model loading, no GPU.
Outputs land in results/figures/ as `.tex` snippets and `.pdf` plots
that can be `\input{}`'d / `\includegraphics{}`'d directly from the
report.

Run from rag-chunk-routing/:

    python -m experiments.make_figures --config configs/base.yaml
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np

from rag_cr import Config, get_logger, load_config
from rag_cr.io import read_jsonl

log = get_logger(__name__)

SIZES_FOR_DISPLAY = [128, 256, 512]
SIZES_INCLUDING_RETIRED = [128, 256, 512, 1024]
TYPES_ORDER = ["factoid", "multihop", "synthesis"]
SPLITS_ORDER = ["train", "val", "test"]

PALETTE = {
    128: "#1f77b4",
    256: "#ff7f0e",
    512: "#2ca02c",
    1024: "#7f7f7f",
}


def _load_json(path: Path) -> Any:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def _fmt(x: float, pct: bool = False, signed: bool = False) -> str:
    if pct:
        return f"{x * 100:.1f}\\%"
    if signed:
        return f"{x:+.2f}"
    return f"{x:.4f}"


def _table_main_results(out_dir: Path, test_summary: dict, oracle_gap: dict) -> None:
    """T1: per-size baselines + Oracle row, on test split."""
    sizes = sorted(int(s) for s in test_summary)
    rows = []
    for size in sizes:
        m = test_summary[str(size)]
        rows.append((str(size), m["n"], m["f1"], m["em"], m["faithfulness"]))

    n_test = oracle_gap["n_questions_test"]
    oracle_f1 = oracle_gap["oracle_f1_mean"]
    rows.append(("Oracle", n_test, oracle_f1, None, None))

    lines = [
        "% Auto-generated by experiments/make_figures.py.",
        "% Source: artifacts/baselines/test_summary.json + oracle_gap.json",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Fixed-size baselines and per-question oracle on the test split "
        f"($n={n_test}$, action space $\\{{128, 256, 512\\}}$). "
        "The oracle picks the best chunk size per question by F1 (tie-break: EM, then smaller size). "
        f"The oracle--best-baseline gap is "
        f"$+{oracle_gap['gap_f1_points']:.2f}$ F1 points.}}",
        "\\label{tab:main-results}",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "System & $n$ & F1 & EM & Faithfulness \\\\",
        "\\midrule",
    ]
    for label, n, f1, em, faith in rows:
        if label == "Oracle":
            lines.append(
                f"\\textbf{{{label}}} & {n} & \\textbf{{{f1:.4f}}} & -- & -- \\\\"
            )
        else:
            lines.append(
                f"Fixed (size = {label}) & {n} & {f1:.4f} & {em:.4f} & {faith:.4f} \\\\"
            )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out_dir / "table_main_results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _table_per_type(out_dir: Path, oracle_gap: dict) -> None:
    """T2: per-type oracle gap on test."""
    per_type = oracle_gap["per_type"]
    lines = [
        "% Auto-generated by experiments/make_figures.py.",
        "% Source: artifacts/baselines/oracle_gap.json (per_type field)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Per-question-type oracle gap on the test split. The "
        "best fixed-size column reports the highest mean F1 across "
        "$\\{128, 256, 512\\}$ for that type; the size in parentheses is "
        "the argmax. Different question types prefer different chunk "
        "sizes, which is the empirical condition under which a router "
        "can recover oracle headroom.}",
        "\\label{tab:per-type-gap}",
        "\\begin{tabular}{lrrrrl}",
        "\\toprule",
        "Type & $n$ & Best fixed F1 & Oracle F1 & Gap (F1 pts) & Best size \\\\",
        "\\midrule",
    ]
    for qtype in TYPES_ORDER:
        m = per_type[qtype]
        per_size = m["per_size_f1"]
        best_size = max(per_size, key=lambda s: per_size[s])
        lines.append(
            f"{qtype} & {m['n_questions']} "
            f"& {m['best_baseline_f1']:.4f} & {m['oracle_f1']:.4f} "
            f"& $+{m['gap'] * 100:.2f}$ & {best_size} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out_dir / "table_per_type_gap.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _table_action_space_ablation(out_dir: Path, og_full: dict, og_restricted: dict) -> None:
    """T3: 4-size vs 3-size action-space ablation."""
    full_overall = og_full["gap_f1_points"]
    restricted_overall = og_restricted["gap_f1_points"]
    sacrifice_overall = restricted_overall - full_overall

    lines = [
        "% Auto-generated by experiments/make_figures.py.",
        "% Source: oracle_gap.json (3-size) + oracle_gap_full.json (4-size)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Action-space ablation on the test split. "
        "The full action space includes the retired chunk size 1024; "
        "the restricted action space is what the router actually uses. "
        "Restricting to three sizes sacrifices "
        f"${sacrifice_overall:+.2f}$ overall F1 points of oracle headroom, "
        "concentrated in multihop and synthesis. We retain the 1024 chunks, "
        "FAISS index, and eval-grid rows so this comparison remains "
        "exactly reproducible.}",
        "\\label{tab:action-space-ablation}",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Type & Full (4 sizes) & Restricted (3 sizes) & Sacrifice \\\\",
        "\\midrule",
    ]
    full_pt = og_full["per_type"]
    restr_pt = og_restricted["per_type"]
    lines.append(
        f"\\textbf{{overall}} & "
        f"\\textbf{{$+{full_overall:.2f}$}} & "
        f"\\textbf{{$+{restricted_overall:.2f}$}} & "
        f"\\textbf{{${sacrifice_overall:+.2f}$}} \\\\"
    )
    lines.append("\\midrule")
    for qtype in TYPES_ORDER:
        f_pts = full_pt[qtype]["gap"] * 100
        r_pts = restr_pt[qtype]["gap"] * 100
        sac = r_pts - f_pts
        lines.append(
            f"{qtype} & $+{f_pts:.2f}$ & $+{r_pts:.2f}$ & ${sac:+.2f}$ \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out_dir / "table_action_space_ablation.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _table_qa_composition(out_dir: Path, manifest: dict) -> None:
    """TA1: splits composition table for the appendix."""
    counts = manifest["split_counts"]
    type_counts = manifest["split_type_counts"]
    total_by_type = {t: sum(type_counts[s].get(t, 0) for s in SPLITS_ORDER) for t in TYPES_ORDER}
    total_by_split = {s: counts.get(s, 0) for s in SPLITS_ORDER}
    grand = manifest["qa_validated_count"]

    lines = [
        "% Auto-generated by experiments/make_figures.py.",
        "% Source: artifacts/splits/manifest.json",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Validated QA-set composition by split and question type. "
        "Stratification is by question type with seed $42$. "
        f"Total is {grand} (not 400) due to a now-fixed offset bug in the "
        "QA-id allocator that produced two duplicate ids; the multihop "
        "duplicates were dropped to keep the eval grid content-consistent. "
        "See \\texttt{README.md} `Why the QA set is 398 and not 400'.}",
        "\\label{tab:qa-composition}",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Split & factoid & multihop & synthesis & total \\\\",
        "\\midrule",
    ]
    for split in SPLITS_ORDER:
        tc = type_counts[split]
        lines.append(
            f"{split} & {tc.get('factoid', 0)} & {tc.get('multihop', 0)} "
            f"& {tc.get('synthesis', 0)} & {total_by_split[split]} \\\\"
        )
    lines.append("\\midrule")
    lines.append(
        f"\\textbf{{total}} & "
        f"{total_by_type['factoid']} & {total_by_type['multihop']} "
        f"& {total_by_type['synthesis']} & \\textbf{{{grand}}} \\\\"
    )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out_dir / "table_qa_composition.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _table_extended_baselines(out_dir: Path, test_summary_full: dict, eval_grid: list) -> None:
    """TA2: per-size baselines including 1024 and mean cost tokens."""
    cost_by_size: dict[int, list[float]] = defaultdict(list)
    for r in eval_grid:
        if r.get("split") != "test":
            continue
        cost_by_size[int(r["chunk_size"])].append(float(r.get("cost_tokens", 0.0)))

    lines = [
        "% Auto-generated by experiments/make_figures.py.",
        "% Source: artifacts/baselines/test_summary_full.json + artifacts/oracle/eval_grid.jsonl",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Extended per-size fixed-baseline metrics on the test split, "
        "all four chunk sizes (including the retired 1024). Cost is the mean "
        "context-token count per question reported by the metrics module.}",
        "\\label{tab:extended-baselines}",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Chunk size & $n$ & F1 & EM & Faithfulness & Mean cost (tokens) \\\\",
        "\\midrule",
    ]
    for size in SIZES_INCLUDING_RETIRED:
        key = str(size)
        if key not in test_summary_full:
            continue
        m = test_summary_full[key]
        cost_vals = cost_by_size.get(size, [])
        cost_mean = sum(cost_vals) / len(cost_vals) if cost_vals else 0.0
        retired = " (retired)" if size == 1024 else ""
        lines.append(
            f"{size}{retired} & {m['n']} & {m['f1']:.4f} & {m['em']:.4f} "
            f"& {m['faithfulness']:.4f} & {cost_mean:.0f} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    (out_dir / "table_extended_baselines.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


