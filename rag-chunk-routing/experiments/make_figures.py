def _figure_size_distribution(out_dir: Path, size_dist: dict) -> None:
    """F1: oracle-best chunk-size distribution per split, grouped bar chart."""
    sizes = SIZES_FOR_DISPLAY
    splits = SPLITS_ORDER
    n_groups = len(splits)
    n_bars = len(sizes)
    bar_width = 0.78 / n_bars
    x = np.arange(n_groups)

    fig, ax = plt.subplots(figsize=(6.0, 3.6))
    for i, size in enumerate(sizes):
        shares = [size_dist[split][str(size)]["share"] * 100 for split in splits]
        offsets = x + (i - (n_bars - 1) / 2) * bar_width
        bars = ax.bar(
            offsets, shares, width=bar_width,
            color=PALETTE[size], label=f"size = {size}", edgecolor="black", linewidth=0.5,
        )
        for bar, share in zip(bars, shares, strict=False):
            ax.annotate(
                f"{share:.1f}%",
                xy=(bar.get_x() + bar.get_width() / 2, bar.get_height()),
                xytext=(0, 2),
                textcoords="offset points",
                ha="center",
                va="bottom",
                fontsize=8,
            )

    ax.set_xticks(x)
    ax.set_xticklabels([s.capitalize() for s in splits])
    ax.set_ylabel("Share of questions where size is oracle-best (%)")
    ax.set_xlabel("Split")
    ax.set_ylim(0, 110)
    ax.set_yticks([0, 20, 40, 60, 80, 100])
    ax.set_axisbelow(True)
    ax.yaxis.grid(True, linestyle="--", alpha=0.4)
    ax.legend(
        loc="lower center",
        bbox_to_anchor=(0.5, 1.02),
        ncol=3,
        frameon=False,
        fontsize=9,
    )
    fig.tight_layout()
    fig.savefig(out_dir / "fig_size_distribution.pdf", bbox_inches="tight")
    fig.savefig(out_dir / "fig_size_distribution.png", dpi=200, bbox_inches="tight")
    plt.close(fig)


def _figure_oracle_f1_distribution(out_dir: Path, eval_grid: list) -> None:
    """FA1: per-question oracle F1 distribution on test, faceted by type."""
    by_type_qa: dict[str, dict[str, float]] = defaultdict(dict)
    for r in eval_grid:
        if r.get("split") != "test":
            continue
        if int(r["chunk_size"]) not in SIZES_FOR_DISPLAY:
            continue
        qid = r["qa_id"]
        f1 = float(r["f1"])
        prev = by_type_qa[r["type"]].get(qid)
        if prev is None or f1 > prev:
            by_type_qa[r["type"]][qid] = f1

    fig, axes = plt.subplots(1, 3, figsize=(7.5, 2.6), sharey=True)
    bins = np.linspace(0, 1, 11)
    for ax, qtype in zip(axes, TYPES_ORDER, strict=False):
        values = list(by_type_qa.get(qtype, {}).values())
        ax.hist(values, bins=bins, color="#4c72b0", edgecolor="black", linewidth=0.5)
        mean_v = float(np.mean(values)) if values else 0.0
        ax.axvline(mean_v, color="#c44e52", linestyle="--", linewidth=1.2,
                   label=f"mean = {mean_v:.3f}")
        ax.set_title(f"{qtype} ($n={len(values)}$)", fontsize=10)
        ax.set_xlabel("Per-question oracle F1")
        ax.set_xlim(0, 1)
        ax.legend(loc="upper right", frameon=False, fontsize=8)
        ax.set_axisbelow(True)
        ax.yaxis.grid(True, linestyle="--", alpha=0.4)
    axes[0].set_ylabel("Count of test questions")
    fig.suptitle(
        "Per-question oracle F1 on the test split, by question type",
        fontsize=10, y=1.02,
    )
    fig.tight_layout()
    fig.savefig(out_dir / "fig_oracle_f1_distribution.pdf", bbox_inches="tight")
    fig.savefig(out_dir / "fig_oracle_f1_distribution.png", dpi=200, bbox_inches="tight")
    plt.close(fig)


