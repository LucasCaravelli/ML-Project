def main(config: Config) -> None:
    """Generate report-ready tables and figures from baseline / oracle artifacts."""
    artifacts_dir = config.paths.artifacts_dir
    baselines_dir = artifacts_dir / "baselines"
    oracle_dir = artifacts_dir / "oracle"
    splits_dir = artifacts_dir / "splits"

    required = [
        baselines_dir / "test_summary.json",
        baselines_dir / "test_summary_full.json",
        baselines_dir / "oracle_gap.json",
        baselines_dir / "oracle_gap_full.json",
        baselines_dir / "size_distribution.json",
        oracle_dir / "eval_grid.jsonl",
        splits_dir / "manifest.json",
    ]
    missing = [p for p in required if not p.exists()]
    if missing:
        log.error("Missing required artifacts:\n%s", "\n".join(f"  {p}" for p in missing))
        log.error("Run experiments/run_baselines.py (canonical and --out-suffix _full) first.")
        sys.exit(2)

    out_dir = Path(config.paths.results_dir) / "figures"
    out_dir.mkdir(parents=True, exist_ok=True)

    test_summary = _load_json(baselines_dir / "test_summary.json")
    test_summary_full = _load_json(baselines_dir / "test_summary_full.json")
    oracle_gap = _load_json(baselines_dir / "oracle_gap.json")
    oracle_gap_full = _load_json(baselines_dir / "oracle_gap_full.json")
    size_dist = _load_json(baselines_dir / "size_distribution.json")
    manifest = _load_json(splits_dir / "manifest.json")
    eval_grid = read_jsonl(oracle_dir / "eval_grid.jsonl")

    log.info("Writing tables and figures to %s", out_dir)

    # Main paper
    _table_main_results(out_dir, test_summary, oracle_gap)
    _table_per_type(out_dir, oracle_gap)
    _table_action_space_ablation(out_dir, oracle_gap_full, oracle_gap)
    _figure_size_distribution(out_dir, size_dist)

    # Appendix
    _table_qa_composition(out_dir, manifest)
    _table_extended_baselines(out_dir, test_summary_full, eval_grid)
    _table_reproducibility(out_dir, config, manifest)
    _figure_oracle_f1_distribution(out_dir, eval_grid)

    _index_readme(out_dir)

    log.info("Done. Files in %s:", out_dir)
    for p in sorted(out_dir.iterdir()):
        log.info("  %s", p.name)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/base.yaml")
    args = parser.parse_args()
    main(load_config(args.config))
